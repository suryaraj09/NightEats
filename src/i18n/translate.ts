export const dictionaries: Record<Lang, Record<Key, string>> = { gu, en };

export const LANGS: Lang[] = ['gu', 'en'];
export const DEFAULT_LANG: Lang = 'gu';

export type Params = Record<string, string | number>;
export type T = (key: Key, params?: Params) => string;

export function isLang(v: unknown): v is Lang {
  return v === 'gu' || v === 'en';
}

/** Look a key up in one language and fill in `{placeholders}`. */
export function translate(lang: Lang, key: Key, params?: Params): string {
  const text = dictionaries[lang][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

/** A `t` function bound to one language (also used by tests and by code outside React). */
export const translator = (lang: Lang): T => (key, params) => translate(lang, key, params);

/** Locale for dates/numbers. */
export const localeOf = (lang: Lang) => (lang === 'gu' ? 'gu-IN' : 'en-IN');
